def class_name(map_name):
    return 'UCEd_' + re.sub(r'\W', '_', map_name)


def path(map_name):
    return STORY / (map_name + '.json')


def load(map_name):
    p = path(map_name)
    if p.exists():
        try:
            value = json.loads(p.read_text(encoding='utf-8'))
        except (OSError, ValueError) as exc:
            raise ValueError('Cannot read this Story: %s. Its saved file has been preserved; restore a valid JSON copy before editing.' % p) from exc
        if not isinstance(value, dict):
            raise ValueError('Invalid Story in %s: expected a JSON object. Its saved file has been preserved.' % p)
        return value
    return dict(route='unatco', dialogues=[], events=[])


def save(map_name, story):
    STORY.mkdir(exist_ok=True)
    atomicfile.write_json(path(map_name), story, ensure_ascii=False)


# ---------------------------------------------------------------- voices given to the lines (dubbing)
def spoken(piece):
    """A piece of a line as the game holds it (what lit() writes, read back)."""
    return str(piece or '').replace('\r', '').replace('\n', ' ').encode('latin1', 'replace').decode('latin1')


def voice_key(speaker, text):
    """The name of a line's own voice in the editor's sounds package: D + UCVoice.Key(speaker|text), as
    UCVoice.Dub looks for it. None for a line the game shows in more than one piece (each piece is a line
    of its own there: split it in the Story to give each its voice)."""
    ps = pieces(text)
    if len(ps) != 1 or not speaker:
        return None
    return raw_voice_key(speaker, spoken(ps[0]))


def raw_voice_key(speaker, text):
    h = 7
    for ch in speaker + '|' + text:
        h = (h * 31 + ord(ch)) % 16777213
    return 'D%d' % h


def line_speaker(d, st):
    """Who says a line of a dialogue in the game: the speaker name dialogue_code gives UCCon.Line."""
    owner = d.get('bind') or ('UCEd_' + ident(d.get('owner')))
    who = st.get('who') or 'npc'
    if who.startswith('actor:'):
        return st.get('bind') or 'UCEd_' + ident(who[6:])
    return owner if who == 'npc' else ('JCDenton' if who == 'jc' else who)


def info_speaker(il):
    """Who says the lines of an InfoLink in the game (UCScene.Say)."""
    return ident(il.get('caller') or 'Unknown')


def voiced_lines(story):
    """(line, speaker) of every line that can have a voice: the lines of dialogues and InfoLinks."""
    for d in story.get('dialogues') or []:
        for st in d.get('steps') or []:
            if st.get('type') == 'line':
                yield st, line_speaker(d, st)
            if st.get('type') == 'choice':
                for option in st.get('options') or []:
                    yield option, 'JCDenton'
    for il in story.get('infolinks') or []:
        for line in il.get('lines') or []:
            yield line, info_speaker(il)


def code(map_name):
    """A short code of the map for names (conversations, flags)."""
    return hashlib.sha1(map_name.lower().encode()).hexdigest()[:4]


def ident(s, fallback='X'):
    """A valid UnrealScript name."""
    s = re.sub(r'\W', '_', str(s or '').strip())
    if not s or s[0].isdigit():
        s = fallback + '_' + s
    return s[:60]


def lit(s):
    """A string literal (Latin-1, quotes escaped)."""
    s = str(s or '').replace('\\', '\\\\').replace('"', '\\"').replace('\r', '').replace('\n', ' ')
    s = s.encode('latin1', 'replace').decode('latin1')
    return '"%s"' % s


def pieces(text, limit=250):
    """Long lines in pieces (UnrealScript string constants: 256 characters at most), cut between
    sentences when possible."""
    text = str(text or '').strip()
    out = []
    while len(text) > limit:
        cut = max(text.rfind('. ', 0, limit), text.rfind('? ', 0, limit), text.rfind('! ', 0, limit))
        if cut < limit // 3:
            cut = text.rfind(' ', 0, limit)
        if cut <= 0:
            cut = limit
        out.append(text[:cut + 1].strip())
        text = text[cut + 1:].strip()
    out.append(text)
    return [p for p in out if p]


def con_name(map_name, d):
    if d.get('replaces'):
        return d['replaces']
    return 'UCEd%s_%s' % (code(map_name), ident(d['id']))


INFOS = {}       # the InfoLinks of the story being generated (for the actions that play one)


def heard_flag(map_name, il):
    return 'UCEd%s_%s_Heard' % (code(map_name), ident(il['id']))


def info_function(il):
    return 'PlayInfo_%s' % ident(il['id'])


def done_flag(map_name, e):
    return 'UCEd%s_%s_Done' % (code(map_name), ident(e['id']))


def do_flag(map_name, d, st):
    """The flag a dialogue sets to run its "do" step (its actions start when the conversation ends)."""
    k = next(i for i, s in enumerate(s for s in d.get('steps') or [] if s.get('type') == 'do') if s is st)
    return 'UCEd%s_%s_do%d' % (code(map_name), ident(d['id']), k + 1)


def requires(lines, reqs, indent='\t\t\t'):
    for r in reqs or []:
        if r.get('flag'):
            lines.append("%sc.Require('%s', %s);" % (indent, ident(r['flag']), 'True' if r.get('is', True) else 'False'))


def cond(reqs):
    parts = []
    for r in reqs or []:
        if r.get('flag'):
            parts.append(('GetF(\'%s\')' if r.get('is', True) else '!GetF(\'%s\')') % ident(r['flag']))
    return parts


def dialogue_code(map_name, d, binds):
    """The UCCon calls of one dialogue (inside SetupStory)."""
    import originalstory as original
    owner = d.get('bind') or ('UCEd_' + ident(d.get('owner')))
    cname = con_name(map_name, d)
    bind = '\tA = Plr();' if d.get('owner') == '@player' else "\tA = Bound('%s', %s);" % (ident(d.get('owner')), lit(owner))
    if d.get('disabled'):
        return [bind, "\tReplaceCon(A, '%s');" % cname]
    check = "HasCopy(A, '%s', %s)" % (cname, lit(original.stamp(d))) if d.get('replaces') else "HasCon(A, '%s')" % cname
    L = [bind,
         "\tif (A != None && !%s)" % check,
         '\t{',
         '\t\tc = new(Level) class\'UCCon\';',
         "\t\tc.Begin('%s', %s, False);" % (cname, lit(owner))]
    if d.get('replaces'):
        L.append('\t\tc.ConProp("CreatedBy", %s);' % lit(original.stamp(d)))
    for k, v in (d.get('native') or {}).items():
        if k in ('bdatalinkcon','bfirstperson','bnoninteractive','brandomcamera','bcanbeinterrupted','bcannotbeinterrupted','binvokebump','binvokefrob','binvokesight','binvokeradius','radiusdistance'):
            L.append('\t\tc.ConProp(%s, %s);' % (lit(k),lit(v)))
    requires(L, d.get('requires'), '\t\t')
    if d.get('once', True):
        L.append('\t\tc.Once();')
    for st in d.get('steps') or []:
        t = st.get('type')
        extra = original.event_code(st)
        if extra is not None:
            L += extra
            continue
        if t == 'line':
            who = st.get('who') or 'npc'
            if who.startswith('actor:'):              # another character of the map
                speaker = st.get('bind') or 'UCEd_' + ident(who[6:])
            else:
                speaker = owner if who == 'npc' else ('JCDenton' if who == 'jc' else who)
            to = st.get('to') or (owner if speaker == 'JCDenton' else 'JCDenton')
            texts = [st.get('text','')] if d.get('replaces') or isinstance(st.get('voice'),dict) else pieces(st.get('text'))
            for piece in texts:
                L.append('\t\tc.Line(%s, %s, %s);' % (lit(speaker), lit(to), original.ustr(piece)))
            for k,v in (st.get('native') or {}).items():
                if k in ('bcontinued','bshowitem','bplayanim','speechfont'):
                    L.append('\t\tc.LastProp(%s, %s);' % (lit(k),lit(v)))
        elif t == 'choice':
            # as many answers as wanted (Paul's weapons at Liberty Island: three); an answer with a flag
            # only shows when the flag has that value
            L.append('\t\tc.Choices();')
            if 'clearScreen' in st:
                L.append('\t\tc.LastProp("bClearScreen", %s);' % lit(str(bool(st['clearScreen']))))
            for o in st.get('options') or []:
                if not str(o.get('text') or '').strip():
                    continue
                args = [original.ustr(str(o['text'])), original.ustr(o.get('goto',''))]
                if o.get('flag'):
                    args += ["'%s'" % ident(o['flag']), 'True' if o.get('is', True) else 'False']
                L.append('\t\tc.Answer(%s);' % ', '.join(args))
                L.append('\t\tc.AnswerDetails(%s, %d, %s);' % (lit(o.get('skill','')),int(o.get('skillLevel',0)),str(bool(o.get('displayAsSpeech')))))
                for f in o.get('requires') or []:
                    L.append("\t\tc.AnswerFlag('%s', %s, %d);" % (ident(f['flag']),str(bool(f.get('is',True))),int(f.get('expiration',0))))
        elif t == 'give':
            item = str(st.get('item') or '').strip()
            if re.fullmatch(r'\w+(\.\w+)?', item):
                L.append('\t\tc.Give(%s, %d, %s);' % (lit(item), max(1, int(st.get('count') or 1)), original.ustr(st.get('fail',''))))
                for key in ('from','to'):
                    if key in st: L.append('\t\tc.LastProp(%s, %s);' % (lit(key+'Name'),lit(st[key])))
        elif t == 'label':
            L.append('\t\tc.Label(%s);' % original.ustr(st.get('name','')))
            L.append("\t\tc.NativeEvent('Comment');")
        elif t == 'if':
            L.append("\t\tc.IfFlag('%s', %s, %s);" % (ident(st.get('flag')), 'True' if st.get('is', True) else 'False',
                                                       original.ustr(st.get('goto',''))))
        elif t == 'goto':
            L.append('\t\tc.Jump(%s);' % original.ustr(st.get('label','')))
            if st.get('conversation'): L.append('\t\tc.JumpOriginal(Self, %s);'%lit(st['conversation']))
        elif t == 'flag':
            L.append("\t\tc.SetFlag('%s', %s);" % (ident(st.get('flag')), 'True' if st.get('is', True) else 'False'))
        elif t == 'goal':
            L.append("\t\tc.Goal('%s', %s, %s, %s);" % (ident(st.get('goal'), 'G'), original.ustr(st.get('text')),
                                                    str(bool(st.get('done'))),str(bool(st.get('secondary')))))
        elif t == 'trigger':
            L.append("\t\tc.Trigger('%s');" % ident(st.get('tag')))
        elif t == 'end':
            L.append('\t\tc.EndHere();')
        elif t == 'do':
            L.append("\t\tc.SetFlag('%s', True);" % do_flag(map_name, d, st))
        elif t == 'random':
            labels=st.get('labels') or []
            if not 1 <= len(labels) <= 64: raise ValueError('A random branch needs 1 to 64 labels.')
            L.append('\t\tc.RandomBegin(Self, %s, %s, %s);' % tuple(str(bool(st.get(k))) for k in ('cycle','once','shuffle')))
            L += ['\t\tc.RandomLabel(%s);' % original.ustr(label) for label in labels]
        if t in ('flag','if'):
            for i,f in enumerate(st.get('requires') or []):
                L.append("\t\tc.LastFlags('%s', %s, %d, %s);" % (ident(f['flag']),str(bool(f.get('is',True))),int(f.get('expiration',0)),str(i==0)))
    L += ['\t\tc.Done();', "\t\tReplaceCon(A, '%s', c.con);" % cname if d.get('replaces') else '\t\tc.AttachTo(A);', '\t}']
    return L


def action_code(map_name, a, dialogues, indent, infolinks=None):
    t = a.get('type')
    if t == 'flag':
        return ["%sSetF('%s', %s);" % (indent, ident(a.get('flag')), 'True' if a.get('is', True) else 'False')]
    if t == 'goal':
        return ["%sGoal('%s', %s, %s);" % (indent, ident(a.get('goal'), 'G'), lit(a.get('text')),
                                           'True' if a.get('done') else 'False')]
    if t == 'note':
        return ['%sNote(%s);' % (indent, lit(p)) for p in pieces(a.get('text'))]
    if t == 'message':
        return ['%sMessage(%s);' % (indent, lit(p)) for p in pieces(a.get('text'))]
    if t == 'trigger':
        return ["%sTriggerTag('%s');" % (indent, ident(a.get('tag')))]
    if t == 'talk':
        d = dialogues.get(a.get('dialogue'))
        if d:
            return ["%sTalk('%s', '%s');" % (indent, ident(d.get('owner')), con_name(map_name, d))]
    if t == 'npc' and a.get('actor'):
        n, act = ident(a['actor']), a.get('act') or 'stop'
        if act in ('goto', 'run'):
            at = a.get('at') or [0, 0, 0]
            return ["%s%s('%s', vect(%g, %g, %g), %s);" % (indent, 'NpcWalk' if a.get('nav') else 'NpcGo', n, at[0], at[1], at[2],
                                                            'True' if act == 'run' else 'False')]
        if act in ('attack', 'hostile'):         # one character only (alone: his faction stays out of it)
            return ["%sNpcHostile('%s', %s, %s);" % (indent, n, 'True' if act == 'attack' else 'False',
                                                     'True' if a.get('alone') else 'False')]
        if act == 'neutral':
            return ["%sNpcNeutral('%s');" % (indent, n)]
        orders = dict(stop='Standing', wander='Wandering', follow='Following')
        if act in orders:
            return ["%sNpcOrders('%s', '%s');" % (indent, n, orders[act])]
        if act == 'friend':
            return ["%sNpcFriend('%s');" % (indent, n)]
        if act in ('hide', 'show'):
            return ["%s%s('%s');" % (indent, 'Hide' if act == 'hide' else 'Show', n)]
        if act == 'join' and a.get('faction'):
            return ["%sNpcJoin('%s', '%s');" % (indent, n, ident(a['faction']))]
    if t == 'faction' and a.get('faction'):
        level = {'friendly': '1.0', 'neutral': '0.0', 'hostile': '-1.0'}.get(a.get('act'), '-1.0')
        return ["%sFactionTowards('%s', '%s', %s, %s);" % (indent, ident(a['faction']), ident(a.get('toward') or 'Player'),
                                                         level, 'True' if a.get('fixed') else 'False')]
    if t == 'door' and a.get('actor'):
        what = ['open', 'close', 'lock', 'unlock', 'blow']
        return ["%sDoorDo('%s', %d);" % (indent, ident(a['actor']), what.index(a.get('act')) if a.get('act') in what else 0)]
    if t == 'infolink' and a.get('infolink') and a['infolink'] in (infolinks or {}):
        return ['%s%s();' % (indent, info_function({'id': a['infolink']}))]
    if t == 'cutscene' and re.fullmatch(r'\w+', str(a.get('cutscene') or '')):     # editor/cutscenes.py
        return ["%sPlayCut('%s');" % (indent, a['cutscene'])]
    if t == 'travel' and re.fullmatch(r'\w+', str(a.get('map') or '')):
        url = a['map'] + ('#' + ident(a['tag']) if a.get('tag') else '')
        return ['%sTravelTo(%s);' % (indent, lit(url))]
    return []


def generate(map_name, story):
    """The UnrealScript class of a map's story."""
    dialogues = {d['id']: d for d in story.get('dialogues') or [] if d.get('id') and d.get('owner')}
    cls = class_name(map_name)
    L = [HEADER % map_name + 'class %s extends UCEditorStory;' % cls, '',
         '// dialogues (attached again whenever the game clears them)',
         'function SetupStory()', '{', '\tlocal Actor A;', '\tlocal UCCon c;', '', '\tClearVoiceRefs();']
    import originalstory
    originalstory.validate(story,complete=True)
    for line,speaker in voiced_lines(dict(story,dialogues=[d for d in story.get('dialogues',[]) if not d.get('disabled')])):
        voice=line.get('voice')
        if isinstance(voice,dict):
            ref=originalstory.voice_path(voice)
            if voice.get('text',line.get('text')) == line.get('text') and voice.get('speaker',speaker) == speaker:
                L.append('\tVoiceRef(%s, %s, %s);' % (lit(speaker),originalstory.ustr(line.get('text')),lit(ref)))
    others = {}
    for d in dialogues.values():
        for st in d.get('steps') or []:
            if st.get('type') == 'line' and str(st.get('who') or '').startswith('actor:'):
                others[st['who'][6:]] = st.get('bind') or 'UCEd_' + ident(st['who'][6:])
    if others:
        L.append('\t// the other characters who speak in these dialogues')
        for n, b in sorted(others.items()):
            L.append("\tBound('%s', %s);" % (ident(n), lit(b)))
    # the game plays the first dialogue of a character whose conditions hold, from the head of its list,
    # and every dialogue goes to the head (UCCon.AttachTo): attached from the bottom up, the first one
    # of the editor's list is the first one checked (the panel says "the first from the top plays")
    for d in reversed(list(dialogues.values())):
        L.append('\t// %s' % re.sub(r'[\r\n]', ' ', d.get('title') or d['id'])[:100])
        L += dialogue_code(map_name, d, {})
    if any(d.get('replaces') and not d.get('disabled') for d in dialogues.values()):
        L.append('\tRebindCopyJumps();')
    L += ['}', '']
    infos = {il['id']: il for il in story.get('infolinks') or [] if il.get('id')}
    INFOS.clear()
    INFOS.update(infos)
    for il in infos.values():
        L += ['// InfoLink: %s' % re.sub(r'[\r\n]', ' ', il.get('title') or il['id'])[:100],
              'function %s()' % info_function(il), '{', '\tlocal UCEdInfoLink s;', '',
              "\ts = InfoLink('%s', %s, %s, %s);" % (heard_flag(map_name, il), 'True' if il.get('once', True) else 'False',
                                                     lit(ident(il.get('caller') or 'Unknown')), lit(il.get('name') or '')),
              '\tif (s == None)', '\t\treturn;']
        if il.get('hush') is False:      # "No talking while it plays" off (UCEdInfoLink hushes by default)
            L.append('\ts.bHushTalks = False;')
        for line in il.get('lines') or []:
            for piece in [line.get('text','')] if isinstance(line.get('voice'),dict) else pieces(line.get('text')):
                L.append('\ts.AddLine(%s);' % originalstory.ustr(piece))
        acts = [a for a in il.get('do') or [] if not (a.get('type') == 'infolink' and a.get('infolink') == il['id'])]
        if acts:
            L.append('\t// at the start: an interrupted InfoLink counts as heard')
        for a in acts:
            L += action_code(map_name, a, dialogues, '\t', INFOS)
        L += ['}', '']
    starts = [e for e in story.get('events') or [] if (e.get('when') or {}).get('type') == 'start']
    others = [e for e in story.get('events') or [] if (e.get('when') or {}).get('type') != 'start']
    L += ['// events at the start of the map', 'function StartStory()', '{']
    for e in starts:
        L += event_code(map_name, e, dialogues)
    L += ['}', '', '// events and dialogues that start when JC comes near', 'function TickStory()', '{',
          '\tif (Talking())', '\t\treturn;']
    for d in dialogues.values():
        if d.get('start') == 'near':
            L.append("\tif (NearTalk(ActorNamed('%s'), '%s', %d))" % (ident(d.get('owner')), con_name(map_name, d),
                                                                      int(d.get('radius') or 200)))
            L.append('\t\treturn;')
    for d in dialogues.values():
        for st in d.get('steps') or []:
            if st.get('type') == 'do':
                f = do_flag(map_name, d, st)
                L += ['\t// %s: actions at the end of the dialogue' % re.sub(r'[\r\n]', ' ', d.get('title') or d['id'])[:80],
                      "\tif (GetF('%s'))" % f, '\t{', "\t\tSetF('%s', False);" % f]
                for a in st.get('do') or []:
                    L += action_code(map_name, a, dialogues, '\t\t', INFOS)
                L.append('\t}')
    for e in others:
        L += event_code(map_name, e, dialogues)
    L += ['}', '', 'defaultproperties', '{', '     bRouteOnly=%s' % ('True' if story.get('route', 'unatco') == 'unatco' and not settings.STANDALONE
                                                                       else 'False'), '}', '']
    return '\n'.join(L)


def event_code(map_name, e, dialogues):
    w = e.get('when') or {}
    c = cond(e.get('requires'))
    if e.get('once', True):
        c.insert(0, "!GetF('%s')" % done_flag(map_name, e))
    if w.get('type') == 'near':
        at = w.get('at') or [0, 0, 0]
        c.append('Near(vect(%g, %g, %g), %d)' % (at[0], at[1], at[2], int(w.get('radius') or 256)))
    elif w.get('type') == 'flag' and w.get('flag'):
        c.append(("GetF('%s')" if w.get('is', True) else "!GetF('%s')") % ident(w['flag']))
    elif w.get('type') == 'dead' and w.get('actor'):
        c.append("Dead('%s')" % ident(w['actor']))
    elif w.get('type') == 'hostile' and w.get('faction'):
        c.append("FactionHostile('%s')" % ident(w['faction']))
    elif w.get('type') == 'item' and re.fullmatch(r'\w+(\.\w+)?', str(w.get('item') or '')):
        c.append('HasItem(%s)' % lit(w['item']))
    L = ['\t// %s' % re.sub(r'[\r\n]', ' ', e.get('title') or e.get('id', ''))[:100],
         '\tif (%s)' % (' && '.join(c) if c else 'True'), '\t{']
    if e.get('once', True):
        L.append("\t\tSetF('%s', True);" % done_flag(map_name, e))
    for a in e.get('do') or []:
        L += action_code(map_name, a, dialogues, '\t\t', INFOS)
    L.append('\t}')
    return L


def write_all():
    """Every story -> its class; classes of stories that are now empty are removed. Returns the lines
    of a report."""
    report = []
    import sys
    sys.path.insert(0,str(KIT/'editor'))
    import sounds
    sounds.write_dub_registry()
    made = set()
    for p in sorted(STORY.glob('*.json')) if STORY.exists() else []:
        map_name = p.stem
        story = load(map_name)
        if not (story.get('dialogues') or story.get('events') or story.get('infolinks')):
            continue
        out = CLASSES / (class_name(map_name) + '.uc')
        out.write_bytes(generate(map_name, story).replace('\n', '\r\n').encode('latin1', 'replace'))
        made.add(out.name)
        report.append('story of %s: %d dialogues, %d InfoLinks, %d events -> %s' % (
            map_name, len(story.get('dialogues') or []), len(story.get('infolinks') or []), len(story.get('events') or []),
            out.name))
    for old in CLASSES.glob('UCEd_*.uc'):
        if old.name not in made:
            old.unlink()
            report.append('removed %s (empty story)' % old.name)
    return report


def known_flags():
    """Flags used by the mod and by the stories (for the editor's suggestions)."""
    names = set()
    isolated = getattr(settings, 'PROJECT_KIND', 'legacy') in ('custom', 'tutorial')
    for f in CLASSES.glob('UCEd_*.uc' if isolated else '*.uc'):
        text = f.read_text(encoding='latin1', errors='replace')
        names.update(re.findall(r"(?:GetF|SetF|SetFlag|Require|IfFlag|GetBool|SetBool)\s*\(\s*'(\w+)'", text))
    for p in STORY.glob('*.json') if STORY.exists() else []:
        names.update(re.findall(r'"flag":\s*"(\w+)"', p.read_text(encoding='utf-8', errors='replace')))
    # Interactions use the same memory as Story. Include them before any rebuild,
    # together with readable automatic dialogue/InfoLink states.
    from editor import statecatalog
    names.update(entry['flag'] for entry in statecatalog.catalog()['flags'])
    # Original text is a local cache, never a source file or a packaged editor asset.
    for p in (() if isolated else (KIT / 'editor/cache/_gamecons').glob('*.json')):
        try:
            names.update(json.loads(p.read_text(encoding='utf-8')).get('flags', {}))
        except (OSError, ValueError):
            pass
    return sorted(names)


