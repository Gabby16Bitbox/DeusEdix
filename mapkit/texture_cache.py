"""Verified image reuse. A cache failure always falls back to making the image.

Generated PCX files keep one recipe receipt beside the output. Preview PNGs keep
one image per texture in the map's last preview; no unbounded image history.
Neither cache is a substitute for building geometry, paths or lighting.
"""
import hashlib
import json
import os
from pathlib import Path
import uuid


def digest(data):
    return hashlib.sha256(data).hexdigest()


def enabled():
    return os.environ.get('DEUSEDIX_TEXTURE_CACHE', 'auto').lower() != 'off'


def _read_json(path):
    try:
        result = json.loads(path.read_bytes())
        return result if isinstance(result, dict) else {}
    except (OSError, ValueError):
        return {}


def _write(path, data):
    """Replace names, never modify a possibly hard-linked file in place."""
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name('.' + path.name + '.' + uuid.uuid4().hex + '.tmp')
    try:
        temp.write_bytes(data)
        os.replace(temp, path)
    finally:
        temp.unlink(missing_ok=True)


def generated(path, recipe, make):
    """Reuse only a deterministic recipe with the exact verified output bytes.

    make receives a private .pcx filename, so failures keep the previous image.
    The receipt describes those private bytes, not a potentially racing writer.
    Unsupported recipe values bypass the cache without changing the generator.
    """
    path = Path(path)
    try:
        key = digest(json.dumps(recipe, sort_keys=True, allow_nan=False).encode('utf-8')) if enabled() else None
    except (TypeError, ValueError):
        key = None
    receipt = path.with_suffix(path.suffix + '.cache.json')
    if key:
        saved = _read_json(receipt)
        try:
            if saved.get('key') == key and saved.get('output') == digest(path.read_bytes()):
                return path
        except OSError:
            pass
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name('.' + path.stem + '.' + uuid.uuid4().hex + '.pcx')
    try:
        make(temp)
        image_hash = digest(temp.read_bytes()) if key else None
        os.replace(temp, path)
        if key:
            try:
                _write(receipt, json.dumps(dict(key=key, output=image_hash)).encode('utf-8'))
            except OSError:
                pass
        # Disabled/uncacheable generation must not retain a matching old receipt.
        else:
            try:
                receipt.unlink(missing_ok=True)
            except OSError:
                pass  # the receipt hash still has to match the regenerated bytes
    finally:
        temp.unlink(missing_ok=True)
    return path


class TexturePreviews:
    """Content-keyed conversions for one map, independent of texture/package names.

    Every lookup hashes the actual BMP/RAW bytes and verifies the stored PNG.
    Updated packages, same-size replacements, transparency and failed exports
    therefore cannot silently reuse a stale image.
    """
    VERSION = 1

    def __init__(self, folder):
        from PIL import __version__
        self.folder = Path(folder)
        self.version = f'{self.VERSION}:{__version__}'
        self.active = enabled()
        self.old = _read_json(self.folder / 'index.json') if self.active else {}
        self.current = {}

    @staticmethod
    def filename(texture):
        return digest(texture.encode('utf-8')) + '.png'

    def convert(self, texture, kind, source, destination, make):
        """make(source, destination) returns True only for a valid conversion."""
        key = digest(self.version.encode() + b'\0' + kind.encode() + b'\0' + source)
        entry = self.old.get(texture)
        cached = self.folder / self.filename(texture)
        if self.active and isinstance(entry, dict) and entry.get('key') == key:
            try:
                png = cached.read_bytes()
                if digest(png) == entry.get('output'):
                    _write(Path(destination), png)
                    self.current[texture] = entry
                    return True
            except OSError:
                pass
        if not make(source, destination):
            return False
        if self.active:
            try:
                png = Path(destination).read_bytes()
                _write(cached, png)
                self.current[texture] = dict(key=key, output=digest(png))
            except OSError:
                pass
        return True

    def finish(self):
        if not self.active:
            return
        try:
            _write(self.folder / 'index.json', json.dumps(self.current).encode('utf-8'))
            for texture in self.old.keys() - self.current.keys():
                (self.folder / self.filename(texture)).unlink(missing_ok=True)
        except OSError:
            pass
