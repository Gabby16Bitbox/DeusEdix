import assert from 'node:assert/strict';
import { crateOnStockpile, textureDone, roomCameras, movingShot, previewedShot, screeningLinked, playerStartInRoom } from '../editor/static/tutorial-checks.js';
import fs from 'node:fs';
const t=JSON.parse(fs.readFileSync(new URL('../tutorial/tutorial.json',import.meta.url),'utf8'));
const reception=t.layout[0], start={name:'UCEdit4',cls:'PlayerStart',loc:[-8,-32,40.5]};
assert.equal(playerStartInRoom([],{},reception),false);
assert.equal(playerStartInRoom([],{added:[start]},reception),true,'user screenshot position is a valid reception spawn');
assert.equal(playerStartInRoom([start],{},reception),true,'rebuilt/base actor also counts');
assert.equal(playerStartInRoom([],{added:[{...start,cls:'Engine.PlayerStart'}]},reception),true,'package-qualified class');
assert.equal(playerStartInRoom([],{added:[start],disabled:{UCEdit4:true}},reception),false);
assert.equal(playerStartInRoom([],{added:[start],deleted:{UCEdit4:true}},reception),false);
assert.equal(playerStartInRoom([],{added:[start],props:{UCEdit4:{bSinglePlayerStart:'False'}}},reception),false);
for (const loc of [[900,0,48],[0,0,-2],[0,0,160],[-248,0,48],[NaN,0,48]])
  assert.equal(playerStartInRoom([start],{moved:{UCEdit4:{loc}}},reception),false,'wrong room, height, wall or invalid transform');
assert.equal(playerStartInRoom([{...start,loc:[900,0,48]}],{moved:{UCEdit4:{loc:start.loc}}},reception),true,'current transform wins');
const spawnLesson=t.steps.find(s=>s.check==='playerstart'), from=spawnLesson.camera.from;
assert.ok(reception.cells.some(([x0,y0,x1,y1])=>from[0]>x0+18&&from[0]<x1-18&&from[1]>y0+18&&from[1]<y1-18),'Show me stays inside reception');
assert.ok(from[2]>48&&from[2]<reception.size[2]-24,'Show me is above the floor and below the ceiling');
assert.equal(spawnLesson.focus.shape,'circle');
assert.equal(playerStartInRoom([],{added:[{...start,loc:[-120,-170,40.5]}]},reception),true,'suggested circle is also valid');
console.log('PASS reception Player Start, saved actors, moves, disabled/deleted, safe Show me, placement circle');
const crate={name:'NewCrate',cls:'DeusEx.CrateUnbreakableSmall',loc:[800,-264,22.5],radius:20,height:20};
const stock={added:[crate]};
assert.equal(crateOnStockpile(stock,t.plate),true,'new crate supported by stockpile');
crate.loc[2]=20.5;
assert.equal(crateOnStockpile(stock,t.plate),false,'floor below the platform is not its top');
crate.loc[2]=70;
assert.equal(crateOnStockpile(stock,t.plate),false,'floating crate is not placed on top');
crate.loc=[725,-264,22.5];
assert.equal(crateOnStockpile(stock,t.plate),false,'crate must fit on the platform');
crate.loc=[800,-264,22.5];
stock.deleted={NewCrate:true};
assert.equal(crateOnStockpile(stock,t.plate),false,'deletion/undo removes completion');
stock.deleted={};
stock.moved={NewCrate:{loc:[500,-264,22.5]}};
assert.equal(crateOnStockpile(stock,t.plate),false,'rebuilt crate moved away no longer qualifies');
stock.moved={};
crate.cls='Chair1';
assert.equal(crateOnStockpile(stock,t.plate),false,'other furniture cannot complete the crate lesson');
console.log('PASS stockpile: crate type, support height, footprint, current transform, deletion');
const room=t.layout[6], name='CameraTest';
const c={keys:[{t:0,p:[-1216,-344,80],r:[0,0,0],fov:75,s:0},{t:4,p:[-1140,-176,64],r:[0,0,0],fov:55,s:0}]};
const e={added:[{name,cls:'UCCutscene'}],cutscenes:{[name]:c},textures:{paint:{pcx:'test.pcx'}},retexture:[]};
assert.equal(textureDone(e,'TutorialTextureCrate'),false,'saving to library is not applying');
e.retexture.push({kind:'actor',name:'TutorialHaleCrate',tex:'paint'});
assert.equal(textureDone(e,'TutorialTextureCrate'),false,'the demonstration is not the exercise');
e.retexture.push({kind:'actor',name:'TutorialTextureCrate',tex:'paint'});
assert.equal(textureDone(e,'TutorialTextureCrate'),true);
assert.equal(roomCameras(e,room).length,1);
assert.equal(movingShot(c),true);
assert.equal(previewedShot(e,room,{}),false,'must preview');
const previews={[name]:JSON.stringify(c.keys)};
assert.equal(previewedShot(e,room,previews),true);
c.keys[1].p[0]-=8;
assert.equal(previewedShot(e,room,previews),false,'changing the shot requires another preview');
e.links=[{src:'TutorialFilmButton',when:'used',do:[{verb:'cutplay',target:name}]}];
assert.equal(screeningLinked(e,room,'TutorialFilmButton'),true);
e.deleted={[name]:true};
assert.equal(screeningLinked(e,room,'TutorialFilmButton'),false);
e.deleted={};
c.keys[1].p[2]=-10;
assert.equal(roomCameras(e,room).length,0,'below-floor camera rejected');
c.keys[1].p=[0,0,64];
assert.equal(roomCameras(e,room).length,0,'camera in another room rejected');
assert.equal(movingShot({keys:[c.keys[0],{...c.keys[0],t:4}]}),false,'identical frames do not make a dramatic move');
console.log('PASS texture application, camera placement, real shot change, complete-preview matching, screening connection, undo/deletion');
